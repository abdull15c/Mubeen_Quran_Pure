def normalize_text(t: str) -> str:
    return t.lower().replace("ё", "е")

def run_test():
    # Let's create an in-memory SQLite DB with FTS
    conn = sqlite3.connect(":memory:")
    c = conn.cursor()
    c.executescript("""
        CREATE VIRTUAL TABLE quran_semantic_fts USING fts4(
            topic_id,
            surah_id,
            ayah_number,
            title,
            note,
            keywords,
            tokenize=unicode61
        );
    """)
    
    rows = []
    for idx, item in enumerate(EXTENDED_SEMANTIC_SITUATIONS, 1):
        topic_title = item["topic"]
        keywords = normalize_text(item["keywords"])
        for surah_id, ayah_num, note in item["ayahs"]:
            rows.append((
                str(idx),
                str(surah_id),
                str(ayah_num),
                topic_title,
                note,
                keywords
            ))
            
    c.executemany("""
        INSERT INTO quran_semantic_fts (topic_id, surah_id, ayah_number, title, note, keywords)
        VALUES (?, ?, ?, ?, ?, ?)
    """, rows)
    
    test_queries = [
        "мне грустно и тяжело",
        "что делать если нарушил обещание",
        "отношения мужа и жены, любовь в семье",
        "деньги в долг",
        "уважение к родителям",
        "как покаяться если согрешил",
        "болезнь и исцеление",
        "страшно и тревожно",
        "умер близкий человек",
        "как брать омовение",
        "почему нельзя делать сплетни",
        "нет денег и работы",
        "как сдержать гнев когда обидели",
        "зависть и высокомерие",
        "пост в рамадан"
    ]
    
    STOP_WORDS = {"мне", "и", "в", "что", "делать", "если", "как", "к", "на", "с", "почему", "нельзя"}
    
    for q in test_queries:
        clean_q = normalize_text(q)
        words = [w for w in re.findall(r"[\w]+", clean_q) if w not in STOP_WORDS and len(w) >= 3]
        if not words:
            continue
            
        terms = [f"{w[:5]}*" if len(w) > 5 else f"{w}*" for w in words]
        match_query = " OR ".join(terms)
        
        all_matches = c.execute("""
            SELECT surah_id, ayah_number, title, note, keywords
            FROM quran_semantic_fts
            WHERE quran_semantic_fts MATCH ?
        """, (match_query,)).fetchall()
        
        # Rank matches by how many query words are contained in (title + keywords + note)
        scored = []
        for surah_id, ayah_number, title, note, keywords in all_matches:
            target_text = normalize_text(f"{title} {keywords} {note}")
            score = 0
            for w in words:
                stem = w[:4] if len(w) >= 4 else w
                if stem in target_text:
                    score += 2 if w in target_text else 1
            scored.append((score, surah_id, ayah_number, title, note))
            
        scored.sort(key=lambda x: x[0], reverse=True)
        top_results = scored[:3]
        
        print(f"\n🔍 ЗАПРОС: «{q}»")
        if not top_results:
            print("  ❌ Ничего не найдено")
        for score, surah, ayah, title, note in top_results:
            print(f"  ✅ [{score}★] {surah}:{ayah} ({title}) -> «{note}»")

if __name__ == "__main__":
    run_test()
