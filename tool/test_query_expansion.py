def clean_word(w: str) -> str:
    return re.sub(r"[^\w\s]", "", w).lower().replace("ё", "е")

def expand_query(raw_query: str) -> list[str]:
    raw_query = clean_word(raw_query)
    words = [w for w in raw_query.split() if w and w not in STOP_WORDS and len(w) > 1]
    
    expanded_terms = set(words)
    for word in words:
        for root, syns in SYNONYMS_AND_INTENTS.items():
            if root in word or word.startswith(root[:4]):
                for s in syns:
                    expanded_terms.add(s)
    return list(expanded_terms)

def test_searches():
    db_gz = Path("assets/db/quran.db.gz")
    tmp_dir = tempfile.mkdtemp()
    tmp_db = Path(tmp_dir) / "test_quran.db"
    try:
        with gzip.open(db_gz, "rb") as f_in, open(tmp_db, "wb") as f_out:
            f_out.write(f_in.read())
        
        conn = sqlite3.connect(tmp_db)
        c = conn.cursor()
        
        test_queries = [
            "мне грустно и тяжело",
            "что делать если нарушил обещание",
            "отношения мужа и жены, любовь в семье",
            "деньги в долг",
            "уважение к родителям",
            "как покаяться если согрешил",
            "болезнь и исцеление",
            "страшно и тревожно"
        ]
        
        for query in test_queries:
            terms = expand_query(query)
            print(f"\n==========================================")
            print(f"USER QUERY: '{query}'")
            print(f"EXPANDED TERMS: {terms}")
            
            # 1. Search in thematic first OR combined FTS
            # Build FTS match: terms with prefix
            match_parts = [f'"{t}"*' if len(t) > 2 else f'"{t}"' for t in terms]
            fts_match = " OR ".join(match_parts)
            
            rows = c.execute(f"""
                SELECT q.kind, q.surah_id, q.ayah_number, q.text, s.name_russian
                FROM quran_search_fts q
                JOIN surahs s ON s.id = CAST(q.surah_id AS INTEGER)
                WHERE q.quran_search_fts MATCH ?
                ORDER BY 
                  CASE WHEN q.kind = 'thematic' THEN 1 ELSE 2 END ASC,
                  q.rowid ASC
                LIMIT 4
            """, (fts_match,)).fetchall()
            
            print(f"TOP RESULTS ({len(rows)}):")
            for r in rows:
                print(f"  [{r[0]}] {r[4]} ({r[1]}:{r[2]}) -> {r[3][:100]}...")
        
        conn.close()
    finally:
        if tmp_db.exists():
            os.remove(tmp_db)
        os.rmdir(tmp_dir)

if __name__ == "__main__":
    test_searches()
